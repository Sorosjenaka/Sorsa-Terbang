const HEADERS = {
  "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36",
  Accept: "text/html,application/xhtml+xml,application/xml;q=0.9,image/avif,image/webp,application/apng,*/*;q=0.8",
  "Accept-Language": "en-US,en;q=0.9"
};

chrome.runtime.onInstalled.addListener(() => {
  registerScript();
});
chrome.runtime.onStartup.addListener(() => {
  registerScript();
});

async function registerScript() {
  try {
    const scripts = await chrome.scripting.getRegisteredContentScripts();
    if (!scripts.some(s => s.id === "scorelens")) {
      await chrome.scripting.registerContentScripts([{
        id: "scorelens",
        js: ["content.js"],
        css: ["styles.css"],
        matches: ["*://*.twitter.com/*", "*://*.x.com/*"],
        runAt: "document_idle"
      }]);
    }
  } catch (e) { console.error("Register failed:", e); }
}

chrome.runtime.onMessage.addListener((msg, sender, sendResponse) => {
  if (msg.type === "GET_SCORE") {
    const url = `https://api.sorsa.io/v1/accounts/search?query=${encodeURIComponent(msg.handle)}&type=twitter`;
    fetch(url)
      .then(r => r.json())
      .then(data => {
        let score = null;
        let followers = null;
        if (data && data.id && data.id !== "7a691d7d-c4f3-4271-9789-e8416655c92d") {
          if (data.score_value != null && data.score_value > 0) {
            score = Math.round(data.score_value).toString();
          }
          if (data.followers != null && data.followers > 0) {
            followers = data.followers.toString();
          }
        }
        sendResponse({ score, followers, url });
      })
      .catch(err => {
        console.error("Sorsa error:", err);
        sendResponse({ score: null, followers: null, error: err.message });
      });
    return true;
  }

  if (msg.type === "GET_TWITTERSCORE") {
    const url = `https://twitterscore.io/twitter/${msg.handle}/overview/`;
    fetch(url, { headers: HEADERS })
      .then(r => r.text())
      .then(html => {
        let score = null;
        const m1 = /const\s+projectScore\s*=\s*([\d.]+)/i.exec(html);
        if (m1) {
          const v = parseFloat(m1[1]);
          if (v > 0 && v <= 1000) {
            score = v < 10 ? v.toFixed(2) : v < 100 ? v.toFixed(1) : Math.ceil(v);
          }
        }
        if (!score) {
          const patterns = [
            /<meta[^>]+(?:name="description"|property="og:description"|name="twitter:description")[^>]+content="([^"]+)"/i,
            /<meta[^>]+content="([^"]+)"[^>]+(?:name="description"|property="og:description"|name="twitter:description")/i
          ];
          for (const p of patterns) {
            const m = p.exec(html);
            if (m) {
              const n = /\b(\d{1,4})\b(?!\s*(?:follower|following|tweet|like|retweet|\d))/i.exec(m[1]);
              if (n) {
                const v = parseInt(n[1], 10);
                if (v > 0 && v <= 1000) { score = v; break; }
              }
            }
          }
        }
        if (!score) {
          const idx = html.indexOf("Score generated by TwitterScore");
          if (idx !== -1) {
            const nums = [...html.substring(Math.max(0, idx - 1000), idx).matchAll(/>\s*([\d.]+)\s*</g)]
              .map(m => parseFloat(m[1])).filter(v => v > 0 && v <= 1000);
            if (nums.length > 0) score = nums[nums.length - 1];
          }
        }
        sendResponse({ score, url });
      })
      .catch(err => {
        console.error("TwitterScore error:", err);
        sendResponse({ score: null, error: err.message });
      });
    return true;
  }
});